import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const context={console,Date};
context.globalThis=context;
runInNewContext(readFileSync('mileage/model.js','utf8'),context);
runInNewContext(readFileSync('mileage/chart.js','utf8'),context);
const Model=context.FleetMileageModel,Chart=context.FleetMileageDailyChart;
const period={from:new Date(2026,10,1,0,0),to:new Date(2026,10,19,18,0),label:'Mês atual'};
const input=[{day:'2026-11-02',km:130},{day:'2026-11-03',km:70},{day:'2026-10-31',km:11},{day:'2026-11-20',km:9}];
const series=Model.dailySeries(input,period);
assert.equal(series.length,19,'Mês até o dia 19 deve mostrar 19 barras, não 10 intervalos');
assert.equal(series[0].day,'2026-11-01');
assert.equal(series[18].day,'2026-11-19');
assert.equal(series[0].km,11,'Viagem que cruza limite é atribuída ao primeiro dia');
assert.equal(series[1].km,130);
assert.equal(series[2].km,70);
assert.equal(series[3].km,0,'Dias sem viagens devem aparecer com 0 km');
assert.equal(series[18].km,9,'Viagem de limite final não pode desaparecer da soma');
assert.equal(series.reduce((sum,r)=>sum+r.km,0),220,'Total diário deve coincidir com a soma da consulta');
const svg=Chart.svg(series);
assert.match(svg,/viewBox/);
assert.match(svg,/01\/11/);
assert.match(svg,/19\/11/);
assert.match(svg,/02\/11: 130,0 km/);
assert.match(svg,/daily-gridline/);
assert.match(svg,/daily-bar-rect/);
assert.equal((svg.match(/class="daily-bar-rect"/g)||[]).length,4);
assert.equal((svg.match(/class="daily-zero-dot"/g)||[]).length,15);
const long=Model.dailySeries([{day:'2026-11-02',km:12}],{from:new Date(2026,8,1),to:new Date(2026,10,19)});
assert.equal(long.length,80,'Períodos longos devem manter um ponto por dia, com rolagem horizontal');
assert.ok(Chart.svg(long).includes('min-width:'),'Gráfico deve poder rolar horizontalmente');
const css=readFileSync('mileage/style.css','utf8');
assert.match(css,/#app \.mileage-dashboard \.trend-panel\s*\{[\s\S]*?background:#ffffff!important/);
assert.match(css,/daily-axis-text/);
const page=readFileSync('mileage/index.html','utf8');
assert.match(page,/Evolução diária da quilometragem/);
assert.match(page,/chart\.js\?v=0\.3\.3/);
assert.ok(readFileSync('mileage/app.js','utf8').includes('Model.dailySeries('));
console.log('OK: evolução diária sem agrupamento, zeros, limites, SVG, cores e rolagem.');
